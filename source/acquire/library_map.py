"""Regenerate the proof desk's library-level import graph from Euler's pinned source.

    python -B -m acquire.library_map [--output PATH]

Besides the library pairs it emits ``depth_layers``: for every module of Main's
closure its shortest import distance from ``Main`` (breadth-first over imports
between submitted modules; Mathlib and core imports are not followed), counted
per depth and per namespace.
"""

import argparse
from collections import Counter, deque
import json
from pathlib import Path
import re
import tarfile

from .prepare import ARCHIVE_HASH, EVIDENCE, INPUT, digest


IMPORT = re.compile(rb"(?:(?:public|private|meta)\s+)*import\s+(.+)")
ASSET = Path(__file__).resolve().parents[1] / "dashboard/static/library-imports.js"
MODULES = 175187


def closure_names():
    return set((EVIDENCE / "main-closure.txt").read_text(encoding="utf-8").splitlines())


def scan_archive(names):
    """Stream the pinned tarball once: {module: [imported submitted modules]}, in archive order."""
    archive = INPUT / "lean.tar.gz"
    if digest(archive) != ARCHIVE_HASH:
        raise ValueError("Archive differs from the pinned Lean source")
    canonical = {name: name for name in names}
    graph = {}
    with tarfile.open(archive, "r|gz") as members:
        for entry in members:
            if not entry.isfile() or not entry.name.startswith("lean/src/") or not entry.name.endswith(".lean"):
                continue
            module = entry.name[len("lean/src/"):-len(".lean")].replace("/", ".")
            if module not in names or module in graph:
                raise ValueError(f"Unexpected source module {module}")
            imports = set()
            source = members.extractfile(entry).read()
            # This archive's generated modules have plain, single-line imports.
            # Reject an unhandled header instead of silently dropping its edges.
            in_header = True
            for line in source.splitlines():
                code = line.partition(b"--")[0].strip()
                match = IMPORT.fullmatch(code)
                if match:
                    if not in_header:
                        raise ValueError(f"Unexpected import outside the header in {module}")
                    imports.update(word.decode() for word in match[1].split() if word != b"all")
                elif code and code not in (b"module", b"prelude"):
                    in_header = False
            graph[canonical[module]] = [canonical[name] for name in sorted(imports & names)]
    if graph.keys() != names or len(graph) != MODULES:
        raise ValueError("Module inventory differs from the Main import closure")
    return graph


def import_depths(graph):
    """Shortest import distance from Main for every module of the closure."""
    depth = {"Main": 0}
    queue = deque(["Main"])
    while queue:
        module = queue.popleft()
        for imported in graph[module]:
            if imported not in depth:
                depth[imported] = depth[module] + 1
                queue.append(imported)
    if depth.keys() != graph.keys():
        raise ValueError("Some closure modules are unreachable from Main")
    return depth


def namespace(module):
    return module.split(".", 1)[0]


def build_map():
    graph = scan_archive(closure_names())
    libraries = Counter(namespace(module) for module in graph)
    edges = Counter((namespace(module), namespace(imported)) for module, imports in graph.items() for imported in imports)
    attested = json.loads((INPUT / "verified.json").read_bytes())
    if attested["archive_sha256"] != ARCHIVE_HASH or dict(libraries) != attested["closure"]["libraries"]:
        raise ValueError("Library counts differ from the pinned source inventory")
    depth = import_depths(graph)
    max_depth = max(depth.values())
    layers = [Counter() for _ in range(max_depth + 1)]
    for module, distance in depth.items():
        layers[distance][namespace(module)] += 1
    return dict(archive_sha256=ARCHIVE_HASH, module_count=len(graph), libraries=dict(sorted(libraries.items())),
                edges=[[source, dependency, count] for (source, dependency), count in sorted(edges.items())],
                max_depth=max_depth,
                depth_layers=[dict(depth=distance, total=sum(layer.values()), by_namespace=dict(sorted(layer.items())))
                              for distance, layer in enumerate(layers)])


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=ASSET, help=f"generated module (default {ASSET})")
    output = parser.parse_args().output
    data = build_map()
    output.write_text("// Generated by python -m acquire.library_map from the pinned Main closure.\n"
                      + "export const libraryImports = " + json.dumps(data, indent=2) + ";\n", encoding="utf-8", newline="\n")
    print(f"{data['module_count']:,} modules, {len(data['edges'])} library pairs, "
          f"{sum(row[2] for row in data['edges']):,} direct submitted-module imports")
    widest = max(data["depth_layers"], key=lambda layer: layer["total"])
    print(f"import depth from Main: 0..{data['max_depth']}, widest layer depth {widest['depth']} "
          f"with {widest['total']:,} modules")


if __name__ == "__main__":
    main()
